local ok, err = pcall(function() error("boom") end)
print(ok, err:match("boom") ~= nil)
local ok2, res = pcall(function() return 42 end)
print(ok2, res)
local ok3, err3 = pcall(function() error({code = 7, msg = "custom"}) end)
print(ok3, type(err3), err3.code, err3.msg)
local ok4, e4 = pcall(function() return nil + 1 end)
print(ok4, type(e4))
local ok5, v = xpcall(function() error("x") end, function(e) return "handled:" .. tostring(e) end)
print(ok5, v:match("handled:") ~= nil)
local ok6 = pcall(function() local t = nil return t.x end)
print(ok6)
print(pcall(function() assert(false, "nope") end))
local function safeDiv(a, b) if b == 0 then return nil, "div0" end return a / b end
print(safeDiv(10, 2))
print(safeDiv(10, 0))
